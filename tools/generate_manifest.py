def generate_manifest():
    books = []
    raw_dir = os.path.join(os.path.dirname(__file__), "..", "data", "raw")

    for cam in range(10, 21):
        tests = []
        for t in range(1, 5):
            t_id = f"cam{cam}_t{t}"
            raw_path = os.path.join(raw_dir, f"{t_id}.json")
            has_audio = True
            if os.path.exists(raw_path):
                with open(raw_path, "r", encoding="utf-8") as f:
                    r_data = json.load(f)
                    has_audio = len(r_data.get("files", {}).get("audio", [])) > 0

            tests.append({
                "id": t_id,
                "title": f"Cambridge IELTS {cam} • Test {t}",
                "badge": "Complete 40 Listening & 40 Reading Questions",
                "has_audio": has_audio
            })

        books.append({
            "id": f"cam{cam}",
            "title": f"Cambridge IELTS {cam}",
            "year": f"Cambridge English Official",
            "badge": "Full 4 Tests • Audio & Reading",
            "tests": tests
        })

    # Legacy topics
    topics_path = os.path.join(os.path.dirname(__file__), "..", "data", "legacy_topics.json")
    with open(topics_path, "r", encoding="utf-8") as f:
        topics = json.load(f)

    manifest_data = {
        "books": books,
        "topics": topics,
        "band_scale": BAND_SCALE
    }

    out_file = os.path.join(os.path.dirname(__file__), "..", "cambridge_data.js")
    js_content = f"""/**
 * Cambridge IELTS Interactive Tests Manifest & B2-C2 Academic Topics
 * Generated by tools/generate_manifest.py
 */
window.CAMBRIDGE_DATA = {json.dumps(manifest_data, ensure_ascii=False, indent=2)};
"""
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"SUCCESS: Generated slim manifest in {out_file} ({os.path.getsize(out_file)} bytes)")

if __name__ == '__main__':
    generate_manifest()
